/** Geriye uyum: dil belirtilmeyen eski cagrilar Turkce havuzu gorur. */
export const QUIPLASH_PROMPTS = QUIPLASH_PROMPTS_TR;

export function getQuiplashPrompts(lang: ContentLang = 'tr'): QuiplashPrompt[] {
  return lang === 'en' ? QUIPLASH_PROMPTS_EN : QUIPLASH_PROMPTS_TR;
}

export function getRandomQuiplashPrompts(count: number = 8, category?: string, lang: ContentLang = 'tr'): QuiplashPrompt[] {
  const all = getQuiplashPrompts(lang);
  let pool = [...all];
  if (category && category !== 'all') {
    pool = pool.filter((p) => p.category === category);
    if (pool.length < count) {
      pool = [...all];
    }
  }
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getRandomLastLashPrompt(lang: ContentLang = 'tr'): QuiplashPrompt {
  // Kategori ADINA gore filtrelemek dile bagliydi: Ingilizce havuzda kategori
  // 'Final Duel' oldugu icin bu filtre bos donerdi ve buyuk final rastgele bir
  // soruya duserdi. id oneki dilden bagimsiz.
  const all = getQuiplashPrompts(lang);
  const finals = all.filter((p) => p.id.startsWith('qp_final_'));
  if (finals.length > 0) {
    return finals[Math.floor(Math.random() * finals.length)];
  }
  return all[Math.floor(Math.random() * all.length)];
}
