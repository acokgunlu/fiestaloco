export function getRandomQuiplashPrompts(count: number = 8, category?: string): QuiplashPrompt[] {
  let pool = [...QUIPLASH_PROMPTS];
  if (category && category !== 'all') {
    pool = pool.filter((p) => p.category === category);
    if (pool.length < count) {
      pool = [...QUIPLASH_PROMPTS];
    }
  }
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getRandomLastLashPrompt(): QuiplashPrompt {
  const finals = QUIPLASH_PROMPTS.filter((p) => p.category === 'Final Düellosu');
  if (finals.length > 0) {
    return finals[Math.floor(Math.random() * finals.length)];
  }
  return QUIPLASH_PROMPTS[Math.floor(Math.random() * QUIPLASH_PROMPTS.length)];
}
