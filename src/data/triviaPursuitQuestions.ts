export const INITIAL_TRIVIA_QUESTIONS = INITIAL_TRIVIA_QUESTIONS_TR;

export function getTriviaQuestions(lang: ContentLang = 'tr'): TriviaQuestion[] {
  return lang === 'en' ? INITIAL_TRIVIA_QUESTIONS_EN : INITIAL_TRIVIA_QUESTIONS_TR;
}

export function getNextTriviaQuestion(
  category: TriviaCategory,
  usedIds: string[],
  questionsPool: TriviaQuestion[] = INITIAL_TRIVIA_QUESTIONS
): TriviaQuestion | null {
  const available = questionsPool.filter(
    (q) => q.category === category && !usedIds.includes(q.id)
  );

  if (available.length > 0) {
    const randomIndex = Math.floor(Math.random() * available.length);
    return available[randomIndex];
  }

  // If none available in this category, pick from any category not used
  const anyAvailable = questionsPool.filter((q) => !usedIds.includes(q.id));
  if (anyAvailable.length > 0) {
    const randomIndex = Math.floor(Math.random() * anyAvailable.length);
    return anyAvailable[randomIndex];
  }

  // If completely exhausted, reset and pick random
  const fallback = questionsPool.filter((q) => q.category === category);
  if (fallback.length > 0) {
    return fallback[Math.floor(Math.random() * fallback.length)];
  }

  return questionsPool[Math.floor(Math.random() * questionsPool.length)];
}
